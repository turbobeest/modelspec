"""Generate the decision JSON Schema and the MCP current-contract constant.

    python -m decision.schema
    python -m decision.schema --check
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from decision.contract import CONTRACT_VERSION, render_json_schema

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_PATH = ROOT / "docs" / "decision-contract.schema.json"
MCP_VERSION_PATH = ROOT / "mcp" / "src" / "contract-version.ts"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated artifacts are stale")
    args = parser.parse_args(argv)
    artifacts = {
        SCHEMA_PATH: render_json_schema(),
        MCP_VERSION_PATH: (
            "// Generated by python -m decision.schema. Do not edit.\n"
            f"export const CURRENT_CONTRACT_VERSION = {json.dumps(CONTRACT_VERSION)};\n"
        ),
    }
    stale = False
    for path, expected in artifacts.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                print(f"stale {path}; run python -m decision.schema")
                stale = True
        else:
            path.write_text(expected, encoding="utf-8")
            print(f"wrote {path}")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
