def build_spec() -> dict[str, Any]:
    # Two real answers, merged: the example request (whose `managed_api` hosting
    # populates `applied.unbound`) and a fully constrained one (which binds every
    # filter and leaves `unbound` empty). Between them every field is seen.
    ranked = _answer(EXAMPLE_REQUEST)
    constrained = _answer({
        "use_case": "coding",
        "environment": {"hardware": "example_device", "hosting": "local", "runtime": "ollama"},
        "constraints": {"max_cost_per_million_input_tokens": 5.0, "price_sensitivity": 0.25,
                        "include_rehosts": True},
        "limit": 2,
    })
    errors = _probe_errors()
    entry_codes = entry_error_codes()

    used: set[str] = set()
    response_schema = _apply_vocabularies(
        _describe(_merge(_infer(ranked), _infer(constrained)), "RankResponse", used))
    row_schema = response_schema["properties"]["result"]["items"]
    response_schema["properties"]["result"]["items"] = _describe(row_schema, "RankedModel", used)

    no_match_schema = _apply_vocabularies(_describe(
        _merge(_infer(errors["no_match"][1]), _infer(errors["insufficient_evidence"][1]))
        ["properties"]["error"], "NoMatchError", used))
    no_match_schema["properties"]["code"]["enum"] = sorted(
        {errors[code][1]["error"]["code"] for code in ("no_match", "insufficient_evidence")})

    refused_codes = ("invalid_request", "unknown_use_case", "unknown_hardware",
                     "unknown_hosting", "unknown_runtime")
    refused: dict[str, Any] = {}
    for code in refused_codes:
        refused = _merge(refused, _infer(errors[code][1])["properties"]["error"])
    refused_schema = _describe(refused, "RequestRefusedError", used)
    refused_schema["properties"]["code"]["enum"] = sorted(
        {errors[code][1]["error"]["code"] for code in refused_codes})

    request_schema = _describe(_request_schema(), "RankRequest", used)
    health_schema = _infer(_health_sample())

    stray = sorted(set(DESCRIPTIONS) - used)
    if stray:
        raise SystemExit(
            "DESCRIPTIONS names field(s) the implementation no longer accepts or returns: "
            + ", ".join(stray))

    def error_envelope(schema: dict[str, Any]) -> dict[str, Any]:
        return {
            "type": "object",
            "required": ["schema_version", "error", "result"],
            "properties": {
                "schema_version": {"type": "string"},
                "service_commit": {"type": "string"},
                "error": schema,
                "result": {"type": "array", "items": {}, "maxItems": 0},
            },
        }

