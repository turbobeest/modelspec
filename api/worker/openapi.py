def _apply_vocabularies(schema: dict[str, Any], name: str | None = None) -> dict[str, Any]:
    """Attach the derived enums wherever those field names appear."""
    if name in VOCABULARIES and schema.get("type") == "string":
        schema = {**schema, "enum": VOCABULARIES[name]()}
    for key, child in (schema.get("properties") or {}).items():
        schema["properties"][key] = _apply_vocabularies(child, key)
    if isinstance(schema.get("items"), dict):
        schema["items"] = _apply_vocabularies(schema["items"], None)
    return schema


def _probe_errors() -> dict[str, tuple[int, dict[str, Any]]]:
    """Run every refusal and keep what came back. Nothing here is written down."""
    out: dict[str, tuple[int, dict[str, Any]]] = {}
    for code, payload in _ERROR_PROBES.items():
        kw = {"only_unrated": True} if code == "insufficient_evidence" else {}
        export = _export(**kw)
        try:
            status, body = service.rank(payload, export, _HARDWARE, _COMMIT, _ORIGIN)
        except service.RequestError as exc:
            status, body = service.error_response(exc, export, _COMMIT, _ORIGIN)
        got = (body.get("error") or {}).get("code")
        if got != code:
            raise SystemExit(
                f"the probe for {code!r} produced {got!r} instead; fix _ERROR_PROBES "
                f"in {Path(__file__).name} before regenerating the spec")
        out[code] = (status, body)

    missing = source_error_codes() - set(out) - _ENTRY_ONLY
    if missing:
        raise SystemExit(
            "the Worker can return error code(s) the spec would not document: "
            + ", ".join(sorted(missing))
            + f". Add a payload to _ERROR_PROBES in {Path(__file__).name}.")
    return out


# ── schema inference ─────────────────────────────────────────────────────────

def _infer(value: Any) -> dict[str, Any]:
    """Describe one JSON value. Deterministic: keys are emitted sorted."""
    if value is None:
        return {"nullable": True}
    if isinstance(value, bool):
        return {"type": "boolean"}
    if isinstance(value, int):
        return {"type": "integer"}
    if isinstance(value, float):
        return {"type": "number"}
    if isinstance(value, str):
        return {"type": "string"}
    if isinstance(value, list):
        schema: dict[str, Any] = {"type": "array"}
        item: dict[str, Any] = {}
        for entry in value:
            item = _merge(item, _infer(entry))
        schema["items"] = item or {}
        return schema
    if isinstance(value, dict):
        properties = {key: _infer(value[key]) for key in sorted(value)}
        return {"type": "object", "required": sorted(value), "properties": properties}
    raise TypeError(f"cannot describe {type(value).__name__}")


def _merge(left: dict[str, Any], right: dict[str, Any]) -> dict[str, Any]:
    """Union two inferred schemas from two sample responses.

    A field seen null in one sample and typed in another is that type, nullable.
    `required` is the intersection: a field one sample omits is optional.
    """
    if not left:
        return dict(right)
    if not right:
        return dict(left)
    out: dict[str, Any] = {}
    nullable = bool(left.get("nullable") or right.get("nullable"))
    type_ = left.get("type") or right.get("type")
    if left.get("type") and right.get("type") and left["type"] != right["type"]:
        # integer and number are the same field seen with and without a fraction.
        type_ = "number" if {left["type"], right["type"]} == {"integer", "number"} else "string"
    if type_:
        out["type"] = type_
    if nullable:
        out["nullable"] = True
    if type_ == "object":
        keys = sorted(set(left.get("properties", {})) | set(right.get("properties", {})))
        out["properties"] = {
            key: _merge(left.get("properties", {}).get(key, {}),
                        right.get("properties", {}).get(key, {}))
            for key in keys
        }
        required = sorted(set(left.get("required", [])) & set(right.get("required", [])))
        if required:
            out["required"] = required
    if type_ == "array":
        out["items"] = _merge(left.get("items", {}), right.get("items", {}))
    return out


def _describe(schema: dict[str, Any], prefix: str, used: set[str]) -> dict[str, Any]:
    """Attach the hand-written prose to the generated schema, by field path."""
    text = DESCRIPTIONS.get(prefix)
    if text:
        schema = {"description": text, **schema}
        used.add(prefix)
    for key, child in (schema.get("properties") or {}).items():
        schema["properties"][key] = _describe(child, f"{prefix}.{key}", used)
    if isinstance(schema.get("items"), dict) and schema["items"].get("properties"):
        # `[]` so an array's own prose is not repeated onto each element.
        schema["items"] = _describe(schema["items"], f"{prefix}[]", used)
    return schema


