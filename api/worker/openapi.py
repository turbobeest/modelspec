def source_error_codes() -> set[str]:
    """Every `error.code` string any Worker module can emit.

    Read from the syntax tree rather than from a list kept beside it, so that
    adding a refusal to the Worker and forgetting the docs is a failed build.
    """
    codes: set[str] = set()
    for path in (SRC / "rank_service.py", SRC / "policy_service.py", SRC / "entry.py"):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            # RequestError("code", "message", ...)
            if isinstance(node, ast.Call):
                name = node.func.id if isinstance(node.func, ast.Name) else None
                if name == "RequestError" and node.args and isinstance(node.args[0], ast.Constant):
                    codes.add(str(node.args[0].value))
            # {"code": "...", ...}
            if isinstance(node, ast.Dict):
                for key, value in zip(node.keys, node.values):
                    if (isinstance(key, ast.Constant) and key.value == "code"
                            and isinstance(value, ast.Constant) and isinstance(value.value, str)):
                        codes.add(value.value)
    return codes


def entry_error_codes() -> dict[str, int]:
    """`code -> HTTP status` for the refusals `entry.py` writes directly."""
    tree = ast.parse((SRC / "entry.py").read_text(encoding="utf-8"))
    found: dict[str, int] = {}
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                and node.func.id == "_json_response" and len(node.args) == 2):
            continue
        status_node, body_node = node.args
        if not (isinstance(status_node, ast.Attribute)
                and status_node.attr.startswith("HTTP_")
                and isinstance(body_node, ast.Dict)):
            continue
        status = getattr(service, status_node.attr, None)
        for key, value in zip(body_node.keys, body_node.values):
            if not (isinstance(key, ast.Constant) and key.value == "error"
                    and isinstance(value, ast.Dict)):
                continue
            for inner_key, inner_value in zip(value.keys, value.values):
                if (isinstance(inner_key, ast.Constant) and inner_key.value == "code"
                        and isinstance(inner_value, ast.Constant) and isinstance(status, int)):
                    found[str(inner_value.value)] = status
    return found


def _value_literals(node: ast.AST) -> set[str]:
    """The string literals an expression can *evaluate to*.

    Only the branches of a conditional count, never its test: in
    `"paid" if why == "tier" else None`, "tier" is compared against, not
    returned, and must not become a permitted value.
    """
    if isinstance(node, ast.Constant):
        return {node.value} if isinstance(node.value, str) else set()
    if isinstance(node, ast.IfExp):
        return _value_literals(node.body) | _value_literals(node.orelse)
    if isinstance(node, ast.BoolOp):
        return set().union(*(_value_literals(v) for v in node.values))
    return set()


def returned_strings(path: Path, function: str) -> list[str]:
    """Every string literal `function` can return, read from its syntax tree.

    `ranking_status`, `rank_status` and `evidence_basis` are closed vocabularies
    a caller branches on, and they are produced by three small functions in the
    scorer. Reading them out of the source beats copying them into this file,
    which is the mistake the whole module exists to avoid.
    """
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name == function:
            found = {
                literal
                for child in ast.walk(node) if isinstance(child, ast.Return) and child.value
                # `return "partial" if ranked else "unavailable"` is two of them.
                for literal in _value_literals(child.value)
            }
            if found:
                return sorted(found)
    raise SystemExit(f"{function} in {path.name} no longer returns string literals; "
                     f"the enum in {Path(__file__).name} cannot be derived")


def dict_key_strings(path: Path, function: str, key: str) -> list[str]:
    """Every string a `{"<key>": ...}` entry inside `function` can carry."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if not (isinstance(node, ast.FunctionDef) and node.name == function):
            continue
        for child in ast.walk(node):
            if not isinstance(child, ast.Dict):
                continue
            for dict_key, dict_value in zip(child.keys, child.values):
                if not (isinstance(dict_key, ast.Constant) and dict_key.value == key):
                    continue
                found = _value_literals(dict_value)
                if found:
                    return sorted(found)
    raise SystemExit(f"{function} in {path.name} no longer builds a {key!r} entry from string "
                     f"literals; the enum in {Path(__file__).name} cannot be derived")


