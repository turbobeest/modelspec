def _answer(payload: dict[str, Any], **kw: Any) -> dict[str, Any]:
    """One response body, produced by the endpoint's own code."""
    export = _export(**kw)
    try:
        _status, body = service.rank(payload, export, _HARDWARE, _COMMIT, _ORIGIN)
    except service.RequestError as exc:
        _status, body = service.error_response(exc, export, _COMMIT, _ORIGIN)
    return body


