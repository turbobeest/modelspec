def _export(use_case: str = "coding", *, only_unrated: bool = False) -> dict[str, Any]:
    """A candidates export in the published shape, from the sandbox fixtures.

    Reusing `access_sandbox._candidates` rather than inventing a second set of
    fixtures keeps this honest in the way that matters: these are
    `pipeline.ranking.Candidate` records, and what comes back out is a
    `rank_report` row with every field a live row has.
    """
    pool = sandbox._candidates(use_case)
    if only_unrated:
        pool = [c for c in pool if not c.benchmark_scores]

    def guide_for(model_id: str) -> dict[str, Any]:
        return {
            "applies_to": {"model_id": model_id, "version": "fixture-1"},
            "as_of": "2026-01-01",
            "status": "current",
            "sections": {
                "prompt_shape": [{
                    "text": "State the task up front.",
                    "sources": [{
                        "url": "https://example.test/sandbox-guide",
                        "title": "Sandbox prompting",
                        "accessed": "2026-01-01",
                        "kind": "provider-guidance",
                    }],
                }],
                "system_message": [],
                "reasoning_and_tools": [],
                "formatting": [],
                "failure_modes": [],
                "retry_advice": [],
            },
        }

    # Guides on the models the spec examples actually rank (flagship when cost
    # is unweighted, fixture-open when price_sensitivity or local hosting binds).
    # Unguided fixtures plus limit=0 keep state=absent / guide=null in the merge.
    return {
        "build": {
            "commit": "0" * 40,
            "built_at": "2026-01-01T00:00:00+00:00",
            "eligibility_as_of": "2026-01-01",
            "export_schema_version": "2.0",
        },
        "candidates": [
            {
                "model_id": c.model_id, "display_name": c.display_name, "provider": c.provider,
                "model_type": c.model_type, "model_subtypes": list(c.model_subtypes),
                "benchmark_scores": dict(c.benchmark_scores),
                "capability_tiers": dict(c.capability_tiers),
                "cost_input": c.cost_input, "context_window": c.context_window,
                "open_weights": c.open_weights, "scores_as_of": c.scores_as_of,
                "fits": {"example_device": True} if c.open_weights else {},
                "verified_benchmarks": sorted(c.verified_benchmarks),
                "rehost_of": c.rehost_of,
            }
            for c in pool
        ],
        "authoring_guides": {
            "sandbox/fixture-flagship": guide_for("sandbox/fixture-flagship"),
            "sandbox/fixture-open": guide_for("sandbox/fixture-open"),
        },
    }


